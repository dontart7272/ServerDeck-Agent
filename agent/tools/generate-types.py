"""Generate structural Go wire types from the checked-in contract snapshots.

SPDX-License-Identifier: Apache-2.0
Union envelopes stay RawMessage; discriminated object branches get separate
types. Only contracts.Decode/Validate makes a value a validated wire message.
"""
import json
import pathlib
import re

BASE = pathlib.Path(__file__).resolve().parents[1] / 'internal/contracts'
def ident(s):
    return ''.join(p[:1].upper()+p[1:] for p in re.split(r'[^a-zA-Z0-9]+', s))
def typename(s, prefix):
    if '$ref' in s:
        name = s['$ref'].split('/')[-1]
        return 'json.RawMessage' if name.startswith('JsonValue') else prefix+ident(name)
    union = s.get('anyOf', s.get('oneOf'))
    if union:
        nonnull = [x for x in union if x.get('type') != 'null']
        if len(nonnull) == 1 and len(union) == 2:
            return '*'+typename(nonnull[0], prefix)
        return 'json.RawMessage'
    kind = s.get('type')
    if 'const' in s:
        kind = 'boolean' if isinstance(s['const'], bool) else 'integer' if isinstance(s['const'], int) else 'string'
    if 'enum' in s and not kind:
        kind = 'string'
    if kind == 'string':
        if s.get('pattern') == '^(0|[1-9][0-9]{0,19})$': return 'U64'
        if s.get('format') == 'date-time': return 'Timestamp'
        return 'string'
    if kind == 'integer': return 'int64'
    if kind == 'number': return 'float64'
    if kind == 'boolean': return 'bool'
    if kind == 'array': return '[]'+typename(s['items'], prefix)
    if kind == 'object':
        if 'properties' not in s: return 'map[string]json.RawMessage'
        fields=[]
        for name, prop in s['properties'].items():
            ty=typename(prop,prefix)
            optional=name not in s.get('required',[])
            if optional and not ty.startswith('*'): ty='*'+ty
            fields.append(f'{ident(name)} {ty} `json:"{name}{",omitempty" if optional else ""}"`')
        return 'struct {\n'+'\n'.join(fields)+'\n}'
    return 'json.RawMessage'

out=['// Code generated by tools/generate-types.py; DO NOT EDIT.',
     '// SPDX-License-Identifier: Apache-2.0', 'package contracts', 'import "encoding/json"']
for family in ['api','ipc','module','ui','release']:
    root=json.loads((BASE/'schemas'/f'{family}.schema.json').read_text(encoding='utf-8'))
    prefix=family.upper()
    definitions=root.get('definitions',{})
    for name,s in [('Document',root),*definitions.items()]:
        if name.startswith('JsonValue'):continue
        ty=typename(s,prefix)
        out.append(f'type {prefix+ident(name)} {"= " if ty == "json.RawMessage" else ""}{ty}')
        for branch in s.get('oneOf',[]):
            props=branch.get('properties',{})
            discriminator=next((props[k]['const'] for k in ('query','action','method','type') if k in props and 'const' in props[k]),None)
            if discriminator: out.append(f'type {prefix+ident(name)+ident(discriminator)} {typename(branch,prefix)}')
(BASE/'wire_generated.go').write_text('\n\n'.join(out)+'\n',encoding='utf-8')
